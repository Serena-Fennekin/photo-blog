import { expect, test } from '@playwright/test'
import sharp from 'sharp'

test('edits public copy and publishes independent moments with revocable private images', async ({ page, browser }) => {
  test.setTimeout(180000)
  await page.goto('/admin/login')
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await page.getByLabel('用户名', { exact: true }).fill('local-e2e-owner')
  await page.getByLabel('密码', { exact: true }).fill('Only-for-isolated-tests-2026!')
  await page.getByRole('button', { name: /创建账号并进入|^登录$/ }).click()
  await expect(page.getByRole('heading', { name: '照片管理' })).toBeVisible()
  const api = page.request
  const initialGallery = await (await api.get('/api/public/gallery')).json()
  const originalCopy = await (await api.get('/api/admin/site-content')).json()
  const visitor = await browser.newContext()
  const publicPage = await visitor.newPage()
  try {
    expect((await visitor.request.get('/api/admin/posts')).status()).toBe(401)
    await page.getByRole('link', { name: '文案设置', exact: true }).click()
    await page.getByLabel('首页引言', { exact: true }).fill('留住今天，\n再看时回到当时。')
    await page.getByLabel('作者名称', { exact: true }).fill('一个记录者')
    await page.getByRole('button', { name: '保存网站文案' }).click()
    await expect(page.getByRole('status')).toContainText('文案已保存')
    await publicPage.goto('/')
    await expect(publicPage.getByRole('heading', { name: /留住今天/ })).toBeVisible()
    await page.getByRole('link', { name: '动态', exact: true }).click()
    await page.getByRole('link', { name: '写一条动态' }).click()
    await page.getByLabel('标题（可选）').fill('小镜头的一天')
    await page.getByLabel('正文', { exact: true }).fill('天气阴阴的，带相机出去走了走。\n<script>不会执行</script>')
    await page.getByLabel('话题').selectOption('gear')
    await page.getByLabel('可见范围').selectOption('private')
    const input = await sharp({ create: { width: 80, height: 120, channels: 3, background: '#749596' } }).jpeg().toBuffer()
    const second = await sharp({ create: { width: 120, height: 80, channels: 3, background: '#97a485' } }).png().toBuffer()
    await page.getByLabel('添加动态图片').setInputFiles([{ name: 'notebook.jpg', mimeType: 'image/jpeg', buffer: input }, { name: 'second.png', mimeType: 'image/png', buffer: second }])
    await expect(page.locator('[data-post-upload]')).toHaveCount(2)
    await page.getByRole('button', { name: '保存私密动态', exact: true }).click()
    await expect(page).toHaveURL(/\/admin\/posts\/[a-f0-9-]+/)
    const post = (await (await api.get('/api/admin/posts')).json()).find((post: any) => post.title === '小镜头的一天')
    expect(post.visibility).toBe('private')
    const ownerPage = await api.get('/admin/posts/' + post.id)
    expect(ownerPage.headers()['cache-control'] || '').toContain('no-store')
    const image = post.images[0].image.src
    expect((await visitor.request.get(image)).status()).toBe(404)
    expect((await visitor.request.get(`/media/${post.images[0].id}/${post.images[0].id}.original`)).status()).toBe(404)
    expect((await visitor.request.get('/api/public/posts/' + post.id)).status()).toBe(404)
    expect((await visitor.request.post('/api/public/posts/' + post.id + '/view')).status()).toBe(404)
    expect((await (await visitor.request.get('/api/public/posts')).json()).items.some((item: any) => item.id === post.id)).toBe(false)
    await page.getByLabel('可见范围').selectOption('public')
    await page.getByRole('button', { name: '发布动态', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('动态已保存')
    const media = await visitor.request.get(image)
    expect(media.status()).toBe(200)
    expect(media.headers()['cache-control']).toContain('no-store')
    expect((await (await api.get('/api/public/gallery')).json()).items).toEqual(initialGallery.items)
    await publicPage.goto('/about')
    const card = publicPage.locator(`[data-post-id="${post.id}"]`)
    await expect(card).toContainText('天气阴阴的')
    await expect(card).toContainText('<script>不会执行</script>')
    await expect(card.locator('script')).toHaveCount(0)
    expect(await card.locator('.moment-body').evaluate(node => parseFloat(getComputedStyle(node).fontSize))).toBeGreaterThanOrEqual(18)
    await card.scrollIntoViewIfNeeded()
    await expect(card.locator('[data-post-views]')).toContainText('1')
    await card.getByRole('button', { name: '查看第1张图片' }).click()
    await expect(publicPage.getByRole('dialog', { name: '动态图片' })).toBeVisible()
    await expect(publicPage.locator('[data-ambient-background]')).toHaveAttribute('data-running', 'false')
    await publicPage.keyboard.press('ArrowRight')
    await expect(publicPage.getByRole('dialog').getByRole('img')).toHaveAttribute('alt', '动态配图2')
    await publicPage.keyboard.press('Escape')
    await expect(publicPage.getByRole('dialog', { name: '动态图片' })).toHaveCount(0)
    await expect(publicPage.locator('[data-ambient-background]')).toHaveAttribute('data-running', 'true')
    await publicPage.reload()
    await card.scrollIntoViewIfNeeded()
    await expect(card.locator('[data-post-views]')).toContainText('1')
    await page.getByLabel('可见范围').selectOption('private')
    await page.getByRole('button', { name: '保存私密动态', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('动态已保存')
    expect((await visitor.request.get(image)).status()).toBe(404)
    await publicPage.reload()
    await expect(publicPage.locator(`[data-post-id="${post.id}"]`)).toHaveCount(0)
    expect((await (await api.get('/api/admin/posts/' + post.id)).json()).viewCount).toBe(1)
    await page.reload()
    await expect(page.getByLabel('可见范围')).toHaveValue('private')
  } finally {
    await api.put('/api/admin/site-content', { data: originalCopy })
    await visitor.close()
  }
})
