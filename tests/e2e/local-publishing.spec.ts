import { expect, test } from '@playwright/test'
import sharp from 'sharp'

test('publishes a batch, protects drafts and originals, counts views, and withdraws', async ({ page, request }) => {
  expect((await request.get('/api/admin/stories')).status()).toBe(401)
  await page.goto('/admin/login')
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await page.getByLabel('用户名', { exact: true }).fill('local-e2e-owner')
  await page.getByLabel('密码', { exact: true }).fill('Only-for-isolated-tests-2026!')
  await page.getByRole('button', { name: /创建账号并进入|^登录$/ }).click()
  await expect(page).toHaveURL(/\/admin$/)
  expect((await page.request.post('/api/admin/stories', { headers: { origin: 'https://other.example' }, data: { title: 'forged' } })).status()).toBe(403)
  await page.getByRole('button', { name: /新建记录/ }).click()
  await expect(page.getByRole('heading', { name: '整理这一刻' })).toBeVisible()
  const slug = `local-test-${Date.now()}`
  await page.getByLabel('标题', { exact: true }).fill('本地发布验收')
  await page.getByLabel('记录链接', { exact: false }).fill(slug)
  await page.getByLabel('地点', { exact: true }).fill('杭州 · 钱塘江')
  const horizontal = await sharp({ create: { width: 960, height: 640, channels: 3, background: '#778d7b' } }).jpeg().toBuffer()
  const portrait = await sharp({ create: { width: 640, height: 900, channels: 3, background: '#c39d81' } }).jpeg().toBuffer()
  let releaseUpload!: () => void
  const uploadGate = new Promise<void>(resolve => { releaseUpload = resolve })
  await page.route('**/api/admin/stories/*/photos', async route => { await uploadGate; await route.continue() })
  await page.locator('#batch-photos').setInputFiles([
    { name: 'river.jpg', mimeType: 'image/jpeg', buffer: horizontal },
    { name: 'portrait.jpg', mimeType: 'image/jpeg', buffer: portrait },
    { name: 'invalid.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not an image') }
  ])
  try { await expect(page.getByLabel('标题', { exact: true })).toBeDisabled(); await expect(page.getByLabel('简短随笔')).toBeDisabled() }
  finally { releaseUpload() }
  await expect(page.locator('.admin-upload-list')).toContainText('失败')
  await expect(page.locator('.admin-photo-card img')).toHaveCount(2)
  await expect(page.locator('.admin-photo-failed')).toHaveCount(1)
  await page.locator('.admin-photo-card').nth(1).getByRole('button', { name: '前移' }).click()
  await page.locator('.admin-photo-card').first().getByRole('radio', { name: '组图封面' }).check()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await request.get(`/api/public/stories/${slug}`)).status()).toBe(404)
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await expect(page.locator('.admin-preview img')).toHaveCount(2)
  await page.getByRole('button', { name: '继续编辑' }).click()
  await page.getByRole('button', { name: '发布记录', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已发布')
  const published = await (await request.get(`/api/public/stories/${slug}`)).json()
  expect(published.photos).toHaveLength(2)
  expect(published.photos[0].image.alt).toBe('portrait')
  expect(JSON.stringify(published)).not.toContain('originalKey')
  expect((await request.get(published.photos[0].image.src)).status()).toBe(200)
  expect((await request.get(`/media/${published.photos[0].id}/original`)).status()).toBe(404)
  const viewURL = `/api/public/photos/${published.photos[0].id}/view`
  expect(await (await request.post(viewURL)).json()).toEqual({ total: 1, counted: true })
  const repeats = await Promise.all(Array.from({ length: 5 }, () => request.post(viewURL)))
  for (const response of repeats) expect(await response.json()).toEqual({ total: 1, counted: false })
  const publicPage = await page.context().newPage()
  await publicPage.goto('/gallery')
  await expect(publicPage.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await publicPage.locator(`[data-photo-id="${published.photos[0].id}"]`).first().click()
  await expect(publicPage.locator('.photo-lightbox__views')).toContainText('2 次查看')
  await publicPage.keyboard.press('ArrowRight')
  await expect(publicPage.locator('[data-active-photo-id]')).toHaveAttribute('data-active-photo-id', published.photos[1].id)
  await publicPage.keyboard.press('Escape')
  await expect(publicPage.getByRole('dialog')).toHaveCount(0)
  await publicPage.close()
  const editorUrl = page.url()
  await page.getByRole('link', { name: '首页设置', exact: true }).click()
  await page.getByRole('radio', { name: '跟随最新发布记录' }).check()
  await page.getByRole('button', { name: '保存首页设置' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await (await request.get('/api/public/home')).json()).settings.heroPhoto.id).toBe(published.cover.id)
  await page.getByRole('radio', { name: '手动选择照片' }).check()
  await page.getByRole('combobox').selectOption(published.photos[1].id)
  await page.getByRole('button', { name: '保存首页设置' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await (await request.get('/api/public/home')).json()).settings.heroPhoto.id).toBe(published.photos[1].id)
  await page.getByRole('link', { name: '分类', exact: true }).click()
  const categorySlug = `category-${Date.now()}`
  await page.getByLabel('分类名称').fill('城市散步')
  await page.getByLabel('英文标识').fill(categorySlug)
  await page.getByRole('button', { name: '新增分类' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await (await request.get('/api/public/gallery')).json()).categories.some((category: { slug: string }) => category.slug === categorySlug)).toBe(true)
  const categoryRow = page.locator('.admin-category-row').last()
  await categoryRow.getByRole('checkbox', { name: '启用' }).uncheck()
  await categoryRow.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await (await request.get('/api/public/gallery')).json()).categories.some((category: { slug: string }) => category.slug === categorySlug)).toBe(false)
  await page.goto(editorUrl)
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await expect(page.locator('.admin-photo-card img')).toHaveCount(2)
  await page.getByRole('button', { name: '撤回为草稿' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await request.get(`/api/public/stories/${slug}`)).status()).toBe(404)
  expect((await request.get(published.photos[0].image.src)).status()).toBe(404)
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/login$/)
  expect((await page.request.get('/api/admin/stories')).status()).toBe(401)
})

test('public navigation uses approved camera and cyclist transitions and clears narrow viewports', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await page.getByRole('link', { name: '摄影集', exact: true }).click()
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-target', 'gallery')
  await expect(page.locator('.camera-scene')).toBeVisible()
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-state', 'idle')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: '关于我', exact: true }).click()
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-target', 'about')
  await expect(page.locator('.cycling-rider')).toBeAttached()
  await page.setViewportSize({ width: 530, height: 700 })
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-state', 'idle')
  await expect(page.locator('.cycling-rider')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '关于我', exact: true })).toBeVisible()
  await expect(page.getByText('EVERY ROAD')).toHaveCount(0)
})
