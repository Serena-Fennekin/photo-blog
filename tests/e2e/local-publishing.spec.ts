import { expect, test } from '@playwright/test'
import sharp from 'sharp'

test('uploads independent photos, edits and publishes them separately, and preserves privacy', async ({ page, request, browser }) => {
  test.setTimeout(120_000)
  expect((await request.get('/api/admin/photos')).status()).toBe(401)
  await page.goto('/admin/login')
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await page.getByLabel('用户名', { exact: true }).fill('local-e2e-owner')
  await page.getByLabel('密码', { exact: true }).fill('Only-for-isolated-tests-2026!')
  await page.getByRole('button', { name: /创建账号并进入|^登录$/ }).click()
  await expect(page.getByRole('heading', { name: '照片管理' })).toBeVisible()
  const api = page.context().request
  for (const photo of await (await api.get('/api/admin/photos')).json()) await api.delete('/api/admin/photos/' + photo.id)
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await expect(page.getByRole('heading', { name: '照片管理' })).toBeVisible()
  expect((await api.post('/api/admin/photos', { headers: { origin: 'https://other.example' }, data: 'forged' })).status()).toBe(403)
  expect((await api.get('/api/admin/stories')).status()).toBe(404)
  const portrait = await sharp({ create: { width: 80, height: 120, channels: 3, background: '#c39d81' } }).withExif({ IFD2: { DateTimeOriginal: '2026:08:19 12:37:12', OffsetTimeOriginal: '+08:00' } }).jpeg().toBuffer()
  const landscape = await sharp({ create: { width: 120, height: 80, channels: 3, background: '#778d7b' } }).png().toBuffer()
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/admin/photos', async route => { if (route.request().method() === 'POST') await gate; await route.continue() })
  const duplicateUpload = page.waitForResponse(response => response.url().endsWith('/api/admin/photos') && response.status() === 409)
  await page.locator('#batch-photos').setInputFiles([
    { name: 'portrait.jpg', mimeType: 'image/jpeg', buffer: portrait },
    { name: 'renamed-portrait.jpg', mimeType: 'image/jpeg', buffer: portrait },
    { name: 'landscape.png', mimeType: 'image/png', buffer: landscape },
    { name: 'invalid.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not an image') }
  ])
  try { await expect(page.locator('#batch-photos')).toBeDisabled(); await expect(page.getByRole('button', { name: '发布所选' })).toBeDisabled() } finally { release() }
  await expect(page.getByRole('status')).toContainText('已上传 2 张独立照片')
  await expect(page.getByRole('status')).toContainText('已跳过 1 张重复照片')
  const duplicate = await (await duplicateUpload).json()
  expect(duplicate.data).toMatchObject({ duplicate: true, existingPhoto: { title: 'portrait', status: 'draft' } })
  await expect(page.locator('.admin-photo-card img')).toHaveCount(2)
  await expect(page.locator('.admin-photo-failed')).toHaveCount(1)
  await expect(page.getByRole('radio')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /新建记录|发布记录/ })).toHaveCount(0)
  const uploaded = await (await api.get('/api/admin/photos')).json()
  const a = uploaded.find((photo: any) => photo.title === 'portrait'), b = uploaded.find((photo: any) => photo.title === 'landscape')
  expect(duplicate.data.existingPhoto.id).toBe(a.id)
  expect(uploaded).toHaveLength(3)
  for (const photo of uploaded) expect(photo).not.toHaveProperty('storyId')
  expect((await (await request.get('/api/public/gallery')).json()).items).toHaveLength(0)
  expect((await request.get('/api/public/photos/' + a.id)).status()).toBe(404)
  expect((await request.get(a.image.src)).status()).toBe(404)
  const cardA = () => page.locator('[data-admin-photo-id="' + a.id + '"]')
  const cardB = () => page.locator('[data-admin-photo-id="' + b.id + '"]')
  await cardA().getByRole('button', { name: '编辑', exact: true }).click()
  await expect(page.getByRole('heading', { name: '编辑照片' })).toBeVisible()
  await page.getByLabel('照片标题', { exact: true }).fill('独立照片A')
  await page.getByLabel('地点', { exact: true }).fill('旧街')
  await page.getByLabel('简短随笔').fill('属于这一张照片的文字')
  await page.getByLabel('人像', { exact: true }).check()
  await page.getByRole('button', { name: '发布照片', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('这张照片已发布')
  expect((await (await request.get('/api/public/gallery')).json()).items.map((photo: any) => photo.id)).toEqual([a.id])
  expect((await (await api.get('/api/admin/photos/' + b.id)).json()).status).toBe('draft')
  await page.getByRole('link', { name: '← 所有照片' }).click()
  await expect(cardA()).toContainText('独立照片A')
  await expect(cardA().locator('.admin-photo-status')).toHaveAttribute('data-status', 'published')
  await expect(cardB().locator('.admin-photo-status')).toHaveAttribute('data-status', 'draft')
  const badgeColor = async (card: ReturnType<typeof cardA>) => card.locator('.admin-photo-status').evaluate(node => getComputedStyle(node).backgroundColor)
  expect(await badgeColor(cardA())).not.toBe(await badgeColor(cardB()))
  await expect(page.getByRole('button', { name: /^(前移|后移)$/ })).toHaveCount(0)
  await cardB().getByRole('checkbox').check()
  await page.getByLabel('统一分类').selectOption('nature')
  await page.getByRole('button', { name: '应用所选分类' }).click()
  await expect(page.getByRole('status')).toContainText('已更新 1 张照片')
  await page.getByRole('button', { name: '发布所选' }).click()
  await expect(cardB()).toContainText('已发布')
  await page.getByRole('button', { name: '发布所选' }).click()
  await expect(page.getByRole('status')).toContainText('均已发布，已跳过重复发布')
  expect((await (await request.get('/api/public/gallery?category=nature')).json()).items.map((photo: any) => photo.id)).toEqual([b.id])
  await cardB().dragTo(cardA())
  await expect(page.locator('[data-admin-photo-id]').first()).toHaveAttribute('data-admin-photo-id', b.id)
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await expect(page.locator('[data-admin-photo-id]').first()).toHaveAttribute('data-admin-photo-id', b.id)
  await cardA().focus()
  await expect(cardA()).toBeFocused()
  await cardA().press('ArrowUp')
  await expect(page.locator('[data-admin-photo-id]').first()).toHaveAttribute('data-admin-photo-id', a.id)
  await expect(cardA()).toBeFocused()
  await expect(page.getByRole('status')).toContainText('第 1 张')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await expect(page.locator('[data-admin-photo-id]').first()).toHaveAttribute('data-admin-photo-id', a.id)
  await cardA().focus()
  await cardA().press('ArrowDown')
  await expect(page.locator('[data-admin-photo-id]').first()).toHaveAttribute('data-admin-photo-id', b.id)
  await expect(cardA()).toBeFocused()
  const publicPhotos = (await (await request.get('/api/public/gallery')).json()).items
  expect(publicPhotos.map((photo: any) => photo.id)).toEqual([b.id, a.id])
  expect(JSON.stringify(publicPhotos)).not.toMatch(/originalKey|storyId|storySlug|coverPhotoId/)
  expect((await request.get('/media/' + a.id + '/original')).status()).toBe(404)
  await page.locator('#batch-photos').setInputFiles([{ name: 'published-photo-renamed.jpg', mimeType: 'image/jpeg', buffer: portrait }])
  await expect(page.getByRole('status')).toContainText('已跳过 1 张重复照片')
  await expect(page.getByRole('link', { name: /查看已有照片：独立照片A/ })).toBeVisible()
  expect(await (await api.get('/api/admin/photos')).json()).toHaveLength(3)
  const visitor = await browser.newContext({ baseURL: 'http://127.0.0.1:3131' }), publicPage = await visitor.newPage()
  try {
    await publicPage.goto('/gallery?photo=' + a.id)
    await expect(publicPage.getByRole('dialog', { name: '照片详情' })).toBeVisible()
    await expect(publicPage.getByText('2026-08-19 12:37')).toBeVisible()
    await expect(publicPage.locator('.photo-lightbox__views')).toContainText('1 次查看')
    expect(await (await visitor.request.post('/api/public/photos/' + a.id + '/view')).json()).toEqual({ total: 1, counted: false })
    await publicPage.getByRole('button', { name: '下一张' }).click()
    await expect(publicPage.locator('[data-active-photo-id]')).toHaveAttribute('data-active-photo-id', b.id)
    await publicPage.keyboard.press('Escape')
    await expect(publicPage.getByRole('dialog')).toHaveCount(0)
  } finally { await visitor.close() }
  await page.getByRole('link', { name: '文案设置', exact: true }).click()
  await page.getByText('旧版精选设置（当前首页不展示）', { exact: true }).click()
  await expect(page.getByRole('radio')).toHaveCount(0)
  await page.getByRole('group', { name: '首页精选（最多6张）' }).getByLabel('独立照片A', { exact: true }).check()
  await page.getByRole('button', { name: '保存首页设置' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  expect((await (await request.get('/api/public/home')).json()).photos.map((photo: any) => photo.id)).toEqual([a.id])
  await page.getByRole('link', { name: '照片', exact: true }).click()
  await expect(page.getByRole('heading', { name: '照片管理' })).toBeVisible()
  await cardA().getByRole('checkbox').check()
  await page.getByRole('button', { name: '撤回所选' }).click()
  await expect(cardA()).toContainText('草稿')
  expect((await request.get('/api/public/photos/' + a.id)).status()).toBe(404)
  expect((await request.get(a.image.src)).status()).toBe(404)
  expect((await (await request.get('/api/public/home')).json()).photos).toEqual([])
  expect((await (await request.get('/api/public/gallery')).json()).items.map((photo: any) => photo.id)).toEqual([b.id])
  await page.reload()
  await expect(cardB()).toContainText('已发布')
  await api.patch('/api/admin/photos/' + b.id, { data: { status: 'draft' } })
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/login$/)
  expect((await page.request.get('/api/admin/photos')).status()).toBe(401)
})

test('public navigation uses the iris and cyclist transitions and clears narrow viewports', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-app-ready', 'true')
  await page.getByRole('link', { name: '摄影集', exact: true }).click()
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-target', 'gallery')
  await expect(page.locator('.aperture-scene')).toBeVisible()
  await expect(page.locator('.camera-scene')).toHaveCount(0)
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-state', 'idle')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: '关于我', exact: true }).click()
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-target', 'about')
  await expect(page.locator('.cycling-rider')).toBeAttached()
  await page.setViewportSize({ width: 530, height: 700 })
  await expect(page.locator('[data-route-curtain]')).toHaveAttribute('data-state', 'idle')
  await expect(page.locator('.cycling-rider')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '关于我', exact: true })).toBeVisible()
  await expect(page.getByText('EVERY ROAD')).toHaveCount(0)
})
