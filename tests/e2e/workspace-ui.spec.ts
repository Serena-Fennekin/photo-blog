import { expect, test, type Page } from '@playwright/test'
import sharp from 'sharp'
import { resolve } from 'node:path'
test.use({actionTimeout:15000})
async function login(page: Page) {
  await page.goto('/admin/login')
  await expect(page.locator('html')).toHaveAttribute('data-app-ready','true')
  await page.getByLabel('用户名',{exact:true}).fill('local-e2e-owner')
  await page.getByLabel('密码',{exact:true}).fill('Only-for-isolated-tests-2026!')
  await page.getByRole('button',{name:/创建账号并进入|^登录$/}).click()
  await expect(page.getByRole('heading',{name:'照片管理'})).toBeVisible()
}
test('persists author identity and topics, returns after publishing, and scrolls only the desktop feed', async ({page,browser}) => {
  test.setTimeout(180000)
  await login(page)
  const api=page.request, ids:string[]=[]
  const title='独立滚动的一天 '+Date.now()
  const label='沿途观察与旅行生活记录'
  const original=await (await api.get('/api/admin/site-content')).json()
  const visitor=await browser.newContext({viewport:{width:1236,height:1244}}), front=await visitor.newPage()
  try {
    expect((await visitor.request.get('/api/admin/post-topics')).status()).toBe(401)
    expect((await visitor.request.post('/api/admin/profile-avatar',{data:Buffer.from('x')})).status()).toBe(401)
    await page.getByRole('link',{name:'文案设置',exact:true}).click()
    await page.getByLabel('作者名称',{exact:true}).fill('骑车的记录者')
    const avatar=await sharp({create:{width:300,height:400,channels:3,background:'#709080'}}).jpeg().toBuffer()
    await page.getByLabel('上传作者头像',{exact:true}).setInputFiles({name:'avatar.jpg',mimeType:'image/jpeg',buffer:avatar})
    await expect(page.getByAltText('作者头像预览')).toHaveAttribute('src',/^data:image\/webp;base64,/)
    await page.getByRole('button',{name:'保存网站文案',exact:true}).click()
    const toast=page.locator('.admin-toast')
    await expect(toast).toContainText('文案已保存')
    await toast.hover()
    await page.waitForTimeout(2100)
    await expect(toast).toBeVisible()
    await page.mouse.move(0,400)
    await page.waitForTimeout(1200)
    await expect(toast).toBeVisible()
    await expect(toast).toBeHidden({timeout:3500})
    const saved=await (await api.get('/api/admin/site-content')).json()
    await page.reload()
    await expect(page.getByLabel('作者名称',{exact:true})).toHaveValue('骑车的记录者')
    await expect(page.getByAltText('作者头像预览')).toHaveAttribute('src',saved.authorAvatar)
    if(process.env.UI_VISUAL)await page.screenshot({path:resolve('.superpowers/sdd/2026-10-30-ui-workspace/settings.png')})
    await page.getByRole('link',{name:'动态',exact:true}).click()
    await page.getByRole('link',{name:'写一条动态',exact:true}).click()
    await page.getByRole('button',{name:'添加话题',exact:true}).click()
    await page.getByLabel('新话题名称',{exact:true}).fill(label)
    await page.getByRole('button',{name:'确认添加',exact:true}).click()
    await expect(page.getByLabel('话题',{exact:true})).not.toHaveValue('life')
    const topic=await page.getByLabel('话题',{exact:true}).inputValue()
    expect(topic).not.toBe('life')
    await page.getByLabel('标题（可选）',{exact:true}).fill(title)
    await page.getByLabel('正文',{exact:true}).fill('骑车经过熟悉的地方，也记下今天的心情。')
    if(process.env.UI_VISUAL)await page.screenshot({path:resolve('.superpowers/sdd/2026-10-30-ui-workspace/editor.png')})
    const publishing=page.waitForResponse(response=>response.url().endsWith('/api/admin/posts')&&response.request().method()==='POST')
    await page.getByRole('button',{name:'发布动态',exact:true}).click()
    const post=await (await publishing).json()
    ids.push(post.id)
    await expect(page).toHaveURL(/\/admin\/posts$/)
    await expect(page.locator('.admin-toast')).toContainText('动态已保存')
    await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible()
    expect(post.topic).toBe(topic)
    await page.goto('/admin/posts/'+post.id)
    await expect(page.getByLabel('话题',{exact:true})).toHaveValue(topic)
    for(let index=0;index<7;index++) {
      const result=await api.post('/api/admin/posts',{data:{title:'滚动检查'+index,body:'停留与出发之间的日常。'.repeat(24),topic:'life',imageIds:[],status:'published',visibility:'public'}})
      ids.push((await result.json()).id)
    }
    await front.goto('/about')
    await expect(front.locator('html')).toHaveAttribute('data-app-ready','true')
    await expect(front.locator('.profile-avatar img')).toHaveAttribute('src',saved.authorAvatar)
    await expect(front.locator('.about-profile__identity h2')).toHaveText('骑车的记录者')
    const first=front.locator('.moment-card').first()
    await expect(first.locator('time')).toContainText(/\d{2}:\d{2}/)
    await expect(first.locator('.moment-avatar img')).toHaveAttribute('src',saved.authorAvatar)
    const scroller=front.locator('.moments-feed__list'), profile=front.locator('.about-profile')
    const start=await profile.boundingBox(), before=await front.evaluate(()=>scrollY)
    await scroller.hover();await front.mouse.wheel(0,700)
    await front.waitForTimeout(80)
    const early=await scroller.evaluate(node=>node.scrollTop)
    await front.waitForTimeout(650)
    expect(await scroller.evaluate(node=>node.scrollTop),'independent scrolling retains the chosen smooth damping').toBeGreaterThan(early+30)
    await expect.poll(()=>scroller.evaluate(node=>node.scrollTop)).toBeGreaterThan(150)
    expect(await front.evaluate(()=>scrollY)).toBe(before)
    expect(Math.abs((await profile.boundingBox())!.y-start!.y)).toBeLessThan(1)
    const target=front.locator(`[data-post-id="${post.id}"]`)
    expect((await (await api.get('/api/admin/posts/'+post.id)).json()).viewCount).toBe(0)
    await scroller.focus()
    await target.scrollIntoViewIfNeeded()
    await expect(target).toBeInViewport()
    await expect(target).toContainText(label)
    await expect(target.locator('[data-post-views]')).toHaveText('1 次浏览')
    await front.getByRole('button',{name:'深色',exact:true}).click()
    await expect(target.locator('.moment-ornament--night')).toBeVisible()
    if(process.env.UI_VISUAL)await front.waitForTimeout(250)
    if(process.env.UI_VISUAL)await front.screenshot({path:resolve('.superpowers/sdd/2026-10-30-ui-workspace/about-dark.png')})
    await front.getByRole('button',{name:'浅色',exact:true}).click()
    await expect(target.locator('.moment-ornament--pond')).toBeVisible()
    if(process.env.UI_VISUAL)await front.waitForTimeout(250)
    if(process.env.UI_VISUAL)await front.screenshot({path:resolve('.superpowers/sdd/2026-10-30-ui-workspace/about-light.png')})
    await front.setViewportSize({width:2560,height:1440})
    await target.scrollIntoViewIfNeeded()
    expect((await front.locator('.about-page').boundingBox())!.width).toBeGreaterThanOrEqual(1800)
    expect(await front.evaluate(()=>document.documentElement.scrollHeight<=innerHeight)).toBe(true)
    if(process.env.UI_VISUAL)await front.screenshot({path:resolve('.superpowers/sdd/2026-10-30-ui-workspace/about-wide.png')})
    await front.setViewportSize({width:393,height:852})
    expect(await scroller.evaluate(node=>getComputedStyle(node).overflowY)).toBe('visible')
    expect(await front.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await target.scrollIntoViewIfNeeded()
    const topicFits=await target.locator('.moment-topic').evaluate(node=>{
      const bounds=node.getBoundingClientRect(), range=document.createRange()
      range.selectNodeContents(node)
      return [...range.getClientRects()].every(line=>line.left>=bounds.left-1&&line.right<=bounds.right+1&&line.bottom<=bounds.bottom+1)
    })
    expect(topicFits,'the complete custom topic must fit within its narrow badge').toBe(true)
    if(process.env.UI_VISUAL)await front.screenshot({path:resolve('.superpowers/sdd/2026-10-30-ui-workspace/about-mobile.png')})
  } finally {
    for(const id of ids) await api.delete('/api/admin/posts/'+id)
    await api.put('/api/admin/site-content',{data:original})
    await visitor.close()
  }
})
